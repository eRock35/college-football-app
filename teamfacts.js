/** ESPN's /rankings -> the AP Top 25, or a throw. Only the AP poll: the
 *  coaches' poll and the CFP ranking are different lists, and mixing them is
 *  how a team ends up #2 on one screen and #1 on the next. */
function normalisePoll(raw) {
  const polls = arr(obj(raw).rankings).map(obj);
  const ap = polls.find((p) => str(p.type, 12).toLowerCase() === 'ap')
    || polls.find((p) => /^ap\b/i.test(str(p.name, 40)) || /^ap\b/i.test(str(p.shortName, 40)));
  if (!ap) throw new Error('no AP poll in the rankings');
  const seenRank = new Set();
  const seenTeam = new Set();
  const ranks = [];
  for (const r of arr(ap.ranks).slice(0, 40).map(obj)) {
    const rank = int(r.current, 1, 25);
    if (rank === null || seenRank.has(rank)) continue;
    const t = espnTeam(r.team);
    if (!t.espnId || seenTeam.has(t.espnId)) continue;
    seenRank.add(rank);
    seenTeam.add(t.espnId);
    const rec = str(obj(r.record).summary || r.recordSummary, 12);
    ranks.push({
      rank,
      espnId: t.espnId,
      teamId: t.teamId,
      team: t.name,
      record: /^\d{1,2}-\d{1,2}(-\d{1,2})?$/.test(rec) ? rec : '',
      previous: int(r.previous, 1, 25),
    });
  }
  ranks.sort((a, b) => a.rank - b.rank);
  if (ranks.length < 10) throw new Error(`AP poll has only ${ranks.length} readable rows`);
  const occ = obj(ap.occurrence);
  return {
    name: 'AP Top 25',
    week: str(occ.displayValue, 30),
    date: isoOrEmpty(ap.date) || isoOrEmpty(ap.lastUpdated),
    ranks,
  };
}

function pollRankOf(poll, espnId) {
  if (!poll || !espnId) return null;
  const hit = poll.ranks.find((r) => r.espnId === espnId);
  return hit ? hit.rank : null;
}

/**
 * The ticker's ranks, from the same poll as the team page. The scoreboard's
 * own curatedRank is ESPN's too, but it moves to the CFP ranking in November
 * while the team page reads the AP poll - and a team shown #4 on the ticker
 * and #6 on its own page is a bug report. With a poll in hand, the poll wins,
 * both ways: a team the poll does not rank is unranked here as well.
 */
function applyPollRanks(result, poll) {
  if (!poll || !result || !result.available) return result;
  const side = (s) => ({ ...s, rank: pollRankOf(poll, s.espnId) });
  const game = (g) => ({ ...g, away: side(g.away), home: side(g.home) });
  return { ...result, games: arr(result.games).map(game), all: arr(result.all).map(game), rankSource: poll.name };
}

/* ------------------------------------------------------------------ *
 * The board's Top 25, from the poll
 * ------------------------------------------------------------------ */

const STATE_PRIORITY = { in: 0, half: 0, delayed: 1, pre: 1, final: 2, postponed: 3, canceled: 3 };

/** The game this week a ranked team is in: live, else the next, else the
 *  last one played. */
function gameFor(espnId, allGames, nowMs) {
  const mine = arr(allGames).filter((g) => g.away.espnId === espnId || g.home.espnId === espnId);
  if (!mine.length) return null;
  return mine.slice().sort((a, b) => (STATE_PRIORITY[a.state] ?? 4) - (STATE_PRIORITY[b.state] ?? 4)
    || (a.state === 'final'
      ? Date.parse(b.startsAt || 0) - Date.parse(a.startsAt || 0)
      : Date.parse(a.startsAt || 0) - Date.parse(b.startsAt || 0)))[0];
}

/**
 * The poll -> rows in the board's `rankings` shape, each with its game this
 * week from the scoreboard. `haveGames` false means the scoreboard could not
 * be read: then an empty game is "not known", not a bye, and the page says so.
 */
function pollRows(poll, allGames, nowMs) {
  return poll.ranks.map((r) => {
    const g = gameFor(r.espnId, allGames, nowMs);
    if (!g) return { rank: r.rank, team: r.team, record: r.record, game: '', time: '', line: '', gameId: '' };
    const home = g.home.espnId === r.espnId;
    const us = home ? g.home : g.away;
    const them = home ? g.away : g.home;
    const oppRank = pollRankOf(poll, them.espnId);
    const opp = (oppRank ? `#${oppRank} ` : '') + them.name;
    const game = (g.neutral ? 'vs ' : home ? 'vs ' : 'at ') + opp;
    let time = '';
    if (g.final && us.score !== null) {
      const o = us.score > them.score ? 'W' : us.score < them.score ? 'L' : 'T';
      time = `Final · ${o} ${us.score}-${them.score}`;
    } else if (g.live && us.score !== null) {
      time = `Live · ${us.score}-${them.score}${g.detail ? ` · ${g.detail}` : ''}`;
    } else if (g.state === 'postponed' || g.state === 'canceled') {
      time = g.state === 'postponed' ? 'Postponed' : 'Canceled';
    } else if (g.startsAt) {
      time = [kickoffLabel(g.startsAt, true), g.tv && g.tv.length ? g.tv[0] : ''].filter(Boolean).join(' · ');
    }
    return {
      rank: r.rank, team: r.team, record: r.record, game, time,
      line: g.state === 'pre' ? str(g.line, 40) : '',
      gameId: '',
      dkUrl: g.dkUrl || '',
    };
  });
}

/** True when the board's own Top 25 should give way to the poll: it has none,
 *  or it was built before the latest poll came out. */
function boardNeedsPoll(boardDoc, poll) {
  if (!poll) return false;
  if (!arr(boardDoc && boardDoc.rankings).length) return true;
  const built = Date.parse((boardDoc && boardDoc.generatedAt) || '');
  const released = Date.parse(poll.date || '');
  return Number.isFinite(released) && (!Number.isFinite(built) || built < released);
}

/* ------------------------------------------------------------------ *
 * Facts over a stored page
 * ------------------------------------------------------------------ */

/** "the Arkansas game", "the Arkansas and Oklahoma games", "the last 3 games". */
function gamesPhrase(names) {
  if (names.length === 1) return `the ${names[0]} game`;
  if (names.length === 2) return `the ${names[0]} and ${names[1]} games`;
  return `the last ${names.length} games`;
}

/** Finished games that ended after `writtenAt`. */
function playedSince(facts, writtenAt) {
  const w = Date.parse(writtenAt || '');
  if (!facts || !Number.isFinite(w)) return [];
  return facts.schedule.filter((r) => r.final && Date.parse(r.date) + GAME_LENGTH_MS > w);
}

/**
 * The page a reader sees: the stored model page (or none) with the facts laid
 * over it. Facts win on record, conference record, rank, schedule and the
 * next game; the model keeps its storyline (dated, and flagged when a game has
 * been played since), its betting line for the next game when it is still the
 * same game, and its rivalry flags.
 *
 * `page` is the stored fan/<id> document or null; `facts` and `poll` are this
 * module's shapes or null. With no facts, the page is returned as it was.
 */
function overlay(page, facts, poll, { teamId, meta, nowMs = Date.now() } = {}) {
  const base = page ? { ...page } : {};
  const out = { ...base, team: teamId, meta, researched: !!page };
  if (!facts) return { ...out, facts: null };

  const modelRows = arr(base.schedule);
  const rivalryWith = new Set(modelRows.filter((r) => r && r.rivalry).map((r) => oppTeamId(r.opp)).filter(Boolean));
  const schedule = facts.schedule.map((r) => {
    const rank = poll ? pollRankOf(poll, r.oppEspnId) : r.oppRank;
    return {
      wk: r.wk, opp: r.opp, loc: r.loc, result: r.result,
      outcome: r.outcome, live: r.live, liveScore: r.liveScore,
      current: r.current, ranked: rank !== null, oppRank: rank,
      rivalry: !!(r.oppTeamId && rivalryWith.has(r.oppTeamId)),
      date: r.date,
    };
  });

  let nextGame = null;
  if (facts.nextGame) {
    const n = facts.nextGame;
    const m = base.nextGame || null;
    // The model's line and board link belong to one game. Kept only while the
    // next game is still that game.
    const nRow = facts.schedule.find((r) => r.id === n.eventId);
    const same = m && nRow && nRow.oppTeamId && oppTeamId(m.opponent) === nRow.oppTeamId;
    const oppRank = poll ? pollRankOf(poll, nRow && nRow.oppEspnId) : n.oppRank;
    nextGame = {
      opponent: n.opponent, oppRank, kickoffISO: n.kickoffISO, kickoffLabel: n.kickoffLabel,
      tv: n.tv, live: n.live, liveScore: n.liveScore, detail: n.detail,
      line: same ? m.line || '' : '', gameId: same ? m.gameId || '' : '',
    };
  }

  const rankNum = poll ? pollRankOf(poll, facts.espnId) : facts.espnRank;
  const since = page ? playedSince(facts, base.lastChecked) : [];
  return {
    ...out,
    rank: rankNum ? `#${rankNum}` : '',
    record: facts.record,
    confRecord: facts.confRecord,
    secRecord: undefined,
    nextGame,
    schedule,
    lastGame: facts.lastGame,
    storylineAsOf: page ? base.lastChecked || '' : '',
    storylineNote: since.length ? `Written before ${gamesPhrase(since.map((r) => r.oppName))} — refresh for a new take` : '',
    storylineStale: since.length > 0,
    facts: {
      source: 'ESPN',
      fetchedAt: facts.fetchedAt || '',
      stale: !!facts.stale,
      rankSource: poll ? `${poll.name}${poll.week ? `, ${poll.week}` : ''}` : (rankNum ? 'ESPN' : ''),
    },
  };
}


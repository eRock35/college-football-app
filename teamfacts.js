/**
 * Team facts: record, schedule, results, next game and rank, from ESPN.
 *
 * WHY THIS EXISTS. A team page (`fan/<id>`) was written by a model with web
 * search, and only when somebody tapped the paid research button. So every
 * fact on it froze the moment it was written: Georgia's page, researched the
 * morning of the Arkansas game, still said 2-0, "next: at Arkansas" and #2 a
 * week later, on the day of the Oklahoma game. Erik: "the uga record is wrong,
 * they beat Arkansas last week".
 *
 * The split that fixes it: FACTS FROM ESPN, PROSE FROM THE MODEL. A record, a
 * score, a kickoff time and a poll position are not opinions; ESPN publishes
 * them for free, keyless, the moment they change. What a model is for is the
 * storyline, and that is shown with the date it was written and a note when a
 * game has been played since.
 *
 * THE SOURCE. The same unofficial family as live.js (site.web.api.espn.com,
 * falling back to site.api on a 403 - see ESPN_HOST there):
 *   - /teams/{espnId}/schedule?season=YYYY  - a team's games and results
 *   - /rankings                              - the AP Top 25 (and others, ignored)
 * Keyless, undocumented, able to change shape without notice. So every field
 * is picked out by name through live.js's own cleaners, bounded, stripped of
 * markup, and the page escapes it all again. Any failure falls back to the
 * last good facts (memory, then Firestore), and then to the model's page as it
 * was - never a 500, never a blank tab.
 *
 * WHICH ESPN TEAM. teams.js ids map to ESPN ids through `espn-ids.js`, a
 * static file generated by `node teamfacts.js --ids <teams.json>` from ESPN's
 * team list (see the bottom of this file). Static because a team's ESPN id
 * does not change and a lookup per cold instance buys nothing. And checked on
 * every fetch: a schedule whose own team does not resolve back to the teams.js
 * id we asked for is refused, so one wrong id in that file shows nothing
 * rather than someone else's season.
 *
 * BILLED PER REQUEST. No timers. The cache (30 min in memory, the same in
 * Firestore so a cold instance does not refetch) is filled by whichever
 * request finds it stale, inside that request.
 *
 * No model call anywhere in here.
 */

const teams = require('./teams');
const live = require('./live');
const { ESPN_IDS, UNMAPPED } = require('./espn-ids');

const { str, int, isoOrEmpty, gameState, obj, arr } = live;

const ESPN_BASE = `${live.ESPN_HOST}/apis/site/v2/sports/football/college-football`;
const TEAMS_URL = `${ESPN_BASE}/teams?groups=80&limit=500`;
const RANKINGS_URL = `${ESPN_BASE}/rankings`;
const scheduleUrl = (espnId, season) => `${ESPN_BASE}/teams/${encodeURIComponent(espnId)}/schedule?season=${season}`;

const TTL_MS = 30 * 60 * 1000;
// A failed fetch is remembered this long, so ESPN being down costs one attempt
// per team per two minutes rather than one per view.
const FAIL_TTL_MS = 2 * 60 * 1000;
const FETCH_TIMEOUT_MS = 6000;
const MAX_BYTES = 3 * 1024 * 1024;
const MAX_EVENTS = 20;
// How long after kickoff a game is assumed to be over, for "was this storyline
// written before that game ended".
const GAME_LENGTH_MS = 4 * 3600 * 1000;

const ESPN_TO_TEAM = new Map(Object.entries(ESPN_IDS).map(([id, espn]) => [espn, id]));

function espnIdFor(teamId) {
  const id = teams.validId(teamId);
  return id ? ESPN_IDS[id] || null : null;
}

/** The season a date belongs to. January is still last season's bowls. */
function seasonFor(nowMs) {
  const d = new Date(nowMs);
  return d.getUTCMonth() === 0 ? d.getUTCFullYear() - 1 : d.getUTCFullYear();
}

const ET = 'America/New_York';
const fmt = (opts) => new Intl.DateTimeFormat('en-US', { timeZone: ET, ...opts });
const WK_FMT = fmt({ month: 'short', day: 'numeric' });
const DAY_FMT = fmt({ weekday: 'short' });
const DATE_FMT = fmt({ weekday: 'short', month: 'short', day: 'numeric' });
const TIME_FMT = fmt({ hour: 'numeric', minute: '2-digit' });

/** "Sat 7:30 PM ET", or "Sat, Nov 7 · time TBA" when ESPN has no time yet. */
function kickoffLabel(iso, timeValid) {
  const t = Date.parse(iso);
  if (!Number.isFinite(t)) return '';
  if (!timeValid) return `${DATE_FMT.format(t)} · time TBA`;
  return `${DAY_FMT.format(t)} ${TIME_FMT.format(t)} ET`;
}


function fetchJson(fetchImpl, url, timeoutMs) {
  return live.fetchEspnJson(fetchImpl, url, timeoutMs, MAX_BYTES);
}

/**
 * `facts(teamId)` and `poll()` each resolve to their shape plus `fetchedAt`
 * and `stale`, or null, and never reject.
 *
 * Order of preference: fresh memory; fresh Firestore (a cold instance); a
 * fetch; on failure the last good copy from either, marked stale. Concurrent
 * callers for one key share one fetch.
 */
function createTeamFacts({ fetch: fetchImpl, db = null, now = Date.now, log = console,
  ttlMs = TTL_MS, failTtlMs = FAIL_TTL_MS, timeoutMs = FETCH_TIMEOUT_MS } = {}) {
  const slots = new Map();
  let upstreamCalls = 0;

  function slot(key) {
    if (!slots.has(key)) slots.set(key, { good: null, failAt: 0, inflight: null, storeRead: false });
    return slots.get(key);
  }

  const fresh = (s) => s.good && now() - s.good.at < ttlMs;
  const serve = (s, stale) => (s.good ? { ...s.good.value, fetchedAt: new Date(s.good.at).toISOString(), stale } : null);

  async function cached(key, ref, load) {
    const s = slot(key);
    if (fresh(s)) return serve(s, false);
    if (!s.good && !s.storeRead && ref) {
      s.storeRead = true;
      try {
        const doc = await ref.get();
        const v = doc.exists ? doc.data() : null;
        const at = v ? Date.parse(v.fetchedAt || '') : NaN;
        if (v && Number.isFinite(at) && !s.good) {
          const { fetchedAt: _f, stale: _s, ...value } = v;
          s.good = { value, at };
        }
      } catch (err) {
        log.error(`[teamfacts] store read ${key} failed:`, err && err.message ? err.message : err);
      }
      if (fresh(s)) return serve(s, false);
    }
    if (s.failAt && now() - s.failAt < failTtlMs) return serve(s, true);
    if (!s.inflight) {
      s.inflight = (async () => {
        upstreamCalls++;
        try {
          const value = await load();
          s.good = { value, at: now() };
          s.failAt = 0;
          if (ref) {
            await ref.set({ ...value, fetchedAt: new Date(s.good.at).toISOString() })
              .catch((err) => log.error(`[teamfacts] store write ${key} failed:`, err && err.message ? err.message : err));
          }
          return serve(s, false);
        } catch (err) {
          s.failAt = now();
          log.error(`[teamfacts] ${key} fetch failed:`, err && err.message ? err.message : err);
          return serve(s, true);
        }
      })().finally(() => { s.inflight = null; });
    }
    return s.inflight;
  }

  async function facts(teamIdRaw) {
    // The only door to Firestore for a team id, as everywhere else.
    const teamId = teams.validId(teamIdRaw);
    const espnId = teamId ? ESPN_IDS[teamId] : null;
    if (!teamId || !espnId) return null;
    const ref = db ? db.collection('teamfacts').doc(teamId) : null;
    return cached(`team:${teamId}`, ref, async () => {
      const raw = await fetchJson(fetchImpl, scheduleUrl(espnId, seasonFor(now())), timeoutMs);
      return normaliseSchedule(raw, teamId, now());
    });
  }

  async function poll() {
    const ref = db ? db.collection('polls').doc('ap') : null;
    return cached('poll:ap', ref, async () => normalisePoll(await fetchJson(fetchImpl, RANKINGS_URL, timeoutMs)));
  }

  return { facts, poll, stats: () => ({ upstreamCalls }) };
}


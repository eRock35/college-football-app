/** An ESPN team object -> { espnId, teamId, name }. A team we know is named
 *  the way the rest of the app names it; anyone else (an FCS opponent) by the
 *  feed's own name, cleaned. */
function espnTeam(raw) {
  const t = obj(raw);
  const espnId = str(t.id, 12);
  const fields = {
    displayName: str(t.displayName, 60), location: str(t.location, 60),
    shortDisplayName: str(t.shortDisplayName, 60), name: str(t.name, 40),
  };
  const byName = live.resolveEspnTeam(fields);
  const byId = ESPN_TO_TEAM.get(espnId) || null;
  // Both must agree when both answer; a disagreement is nobody.
  const teamId = byId && byName && byId !== byName ? null : (byId || byName);
  const meta = teamId ? teams.get(teamId) : null;
  return {
    espnId: /^\d{1,8}$/.test(espnId) ? espnId : '',
    teamId,
    name: meta ? meta.name : (fields.location || fields.shortDisplayName || fields.displayName || 'TBD'),
  };
}

/** "at Arkansas" / "vs Florida (Atlanta)" / "#24 Oklahoma" -> a teams.js id. */
function oppTeamId(text) {
  const s = String(text || '')
    .replace(/\([^)]*\)/g, ' ')
    .replace(/^\s*(at|@|vs\.?|v\.?)\s+/i, '');
  return live.resolveTeam(s);
}

/* ------------------------------------------------------------------ *
 * The team list -> the id map (used to generate espn-ids.js)
 * ------------------------------------------------------------------ */

/** ESPN's /teams response -> { map: {teamId: espnId}, missing, unmatched, conflicts }. */
function buildEspnMap(raw) {
  const rows = arr(obj(arr(obj(arr(obj(raw).sports)[0]).leagues)[0]).teams)
    .map((r) => obj(obj(r).team));
  if (!rows.length) throw new Error('team list has no teams');
  const claims = new Map();
  const unmatched = [];
  for (const t of rows) {
    const espnId = str(t.id, 12);
    if (!/^\d{1,8}$/.test(espnId)) continue;
    const teamId = live.resolveEspnTeam({
      displayName: str(t.displayName, 60), location: str(t.location, 60),
      shortDisplayName: str(t.shortDisplayName, 60), name: str(t.name, 40),
    });
    if (!teamId) { unmatched.push(`${espnId} ${str(t.displayName, 60)}`); continue; }
    if (!claims.has(teamId)) claims.set(teamId, new Set());
    claims.get(teamId).add(espnId);
  }
  const map = {};
  const conflicts = [];
  for (const t of teams.TEAMS) {
    const ids = claims.get(t.id);
    if (ids && ids.size === 1) map[t.id] = [...ids][0];
    else if (ids && ids.size > 1) conflicts.push(`${t.id}: ${[...ids].join(', ')}`);
  }
  const missing = teams.TEAMS.map((t) => t.id).filter((id) => !map[id]);
  return { map, missing, unmatched, conflicts };
}

/* ------------------------------------------------------------------ *
 * A team's schedule
 * ------------------------------------------------------------------ */

/** Scoreboard scores are strings, schedule scores are {value, displayValue}. */
function score(v) {
  if (v && typeof v === 'object') return int(v.displayValue !== undefined ? v.displayValue : v.value, 0, 250);
  return int(v, 0, 250);
}

function tvOf(comp) {
  const out = [];
  for (const b of arr(comp.broadcasts).slice(0, 4)) {
    const o = obj(b);
    const names = [str(obj(o.media).shortName, 16), ...arr(o.names).slice(0, 3).map((n) => str(n, 16))];
    for (const n of names) if (n && !out.includes(n)) out.push(n);
  }
  return out.slice(0, 2).join(' / ');
}

function recordOf(c, type) {
  const r = arr(c.record || c.records).map(obj).find((x) => str(x.type, 20) === type);
  const s = r ? str(r.displayValue || r.summary, 12) : '';
  return /^\d{1,2}-\d{1,2}(-\d{1,2})?$/.test(s) ? s : '';
}

/** One schedule event -> a row, or null when it cannot be read. */
function scheduleRow(raw, espnId) {
  const ev = obj(raw);
  const id = str(ev.id, 20);
  if (!/^\d{1,20}$/.test(id)) return null;
  const comp = obj(arr(ev.competitions)[0]);
  const cs = arr(comp.competitors).map(obj);
  if (cs.length !== 2) return null;
  const usRaw = cs.find((c) => str(c.id, 12) === espnId || str(obj(c.team).id, 12) === espnId);
  const themRaw = cs.find((c) => c !== usRaw);
  if (!usRaw || !themRaw) return null;
  const date = isoOrEmpty(comp.date || ev.date);
  if (!date) return null;
  const status = obj(Object.keys(obj(comp.status)).length ? comp.status : ev.status);
  const state = gameState(status) || 'pre';
  const opp = espnTeam(themRaw.team);
  const neutral = comp.neutralSite === true;
  const loc = neutral ? 'neutral' : str(usRaw.homeAway, 6) === 'away' ? 'away' : 'home';
  const timeValid = !(ev.timeValid === false || comp.timeValid === false);

  const final = state === 'final';
  const live2 = state === 'in' || state === 'half';
  let us = score(usRaw.score);
  let them = score(themRaw.score);
  if (!(final || live2) || us === null || them === null) { us = null; them = null; }
  let outcome = '';
  if (final && us !== null) {
    outcome = usRaw.winner === true ? 'W' : themRaw.winner === true ? 'L' : us > them ? 'W' : us < them ? 'L' : 'T';
  }
  const result = final && us !== null ? `${outcome} ${us}-${them}`
    : state === 'postponed' ? 'Postponed' : state === 'canceled' ? 'Canceled' : '';
  const oppRank = int(obj(themRaw.curatedRank).current, 1, 25);

  return {
    id,
    date,
    wk: WK_FMT.format(Date.parse(date)),
    opp: (loc === 'away' ? 'at ' : loc === 'neutral' ? 'vs ' : '') + opp.name,
    oppName: opp.name,
    oppTeamId: opp.teamId,
    oppEspnId: opp.espnId,
    oppRank,
    loc,
    state,
    final,
    live: live2,
    result,
    outcome,
    liveScore: live2 && us !== null ? `${us}-${them}` : '',
    detail: live2 ? str(obj(status.type).shortDetail || obj(status.type).detail, 40) : '',
    conf: comp.conferenceCompetition === true,
    confKnown: typeof comp.conferenceCompetition === 'boolean',
    ranked: oppRank !== null,
    rivalry: false,
    current: false,
    kickoffISO: timeValid ? date : '',
    kickoffLabel: kickoffLabel(date, timeValid),
    tv: tvOf(comp),
    espnRank: int(obj(usRaw.curatedRank).current, 1, 25),
    confRecordHint: recordOf(usRaw, 'vsconf'),
  };
}

const fmtRecord = (w, l, t) => `${w}-${l}${t ? `-${t}` : ''}`;

/**
 * ESPN's schedule response -> a team's facts. Throws when the response is not
 * for the team asked about - one wrong id in espn-ids.js must show nothing,
 * never someone else's season.
 */
function normaliseSchedule(raw, teamId, nowMs) {
  const espnId = espnIdFor(teamId);
  if (!espnId) throw new Error(`no ESPN id for ${teamId}`);
  const body = obj(raw);
  const who = espnTeam(body.team);
  if (who.espnId !== espnId || (who.teamId && who.teamId !== teamId)) {
    throw new Error(`schedule for ${teamId} came back as ${who.espnId} ${who.name}`);
  }
  if (!Array.isArray(body.events)) throw new Error('schedule has no events list');

  const seen = new Set();
  const rows = [];
  for (const e of body.events.slice(0, MAX_EVENTS)) {
    const r = scheduleRow(e, espnId);
    if (r && !seen.has(r.id)) { seen.add(r.id); rows.push(r); }
  }
  rows.sort((a, b) => Date.parse(a.date) - Date.parse(b.date));
  if (!rows.length) throw new Error('schedule has no readable games');

  let w = 0, l = 0, t = 0, cw = 0, cl = 0, ct = 0;
  for (const r of rows) {
    if (!r.outcome) continue;
    if (r.outcome === 'W') w++; else if (r.outcome === 'L') l++; else t++;
    if (r.conf) { if (r.outcome === 'W') cw++; else if (r.outcome === 'L') cl++; else ct++; }
  }
  const finals = rows.filter((r) => r.outcome);
  // Conference record: counted from the games when ESPN flags conference
  // games, otherwise ESPN's own vs-conference split on the latest final.
  const confKnown = rows.some((r) => r.confKnown);
  const lastFinal = finals[finals.length - 1] || null;
  const confRecord = confKnown ? fmtRecord(cw, cl, ct) : (lastFinal ? lastFinal.confRecordHint : '');

  // This week's game: one in progress, else the next one not yet played.
  const upcoming = rows.filter((r) => r.live || (r.state === 'pre' || r.state === 'delayed'));
  const current = upcoming[0] || null;
  if (current) current.current = true;
  const espnRank = (current && current.espnRank) || (lastFinal && lastFinal.espnRank) || null;

  return {
    teamId,
    espnId,
    season: seasonFor(nowMs),
    record: fmtRecord(w, l, t),
    confRecord,
    espnRank,
    schedule: rows.map(({ confKnown: _k, confRecordHint: _h, espnRank: _r, ...row }) => row),
    nextGame: current ? {
      eventId: current.id,
      opponent: current.opp,
      oppName: current.oppName,
      oppRank: current.oppRank,
      loc: current.loc,
      kickoffISO: current.kickoffISO,
      kickoffLabel: current.kickoffLabel,
      tv: current.tv,
      state: current.state,
      live: current.live,
      liveScore: current.liveScore,
      detail: current.detail,
    } : null,
    lastGame: lastFinal ? { eventId: lastFinal.id, oppName: lastFinal.oppName, result: lastFinal.result, date: lastFinal.date } : null,
  };
}

